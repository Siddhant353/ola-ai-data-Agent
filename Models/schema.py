#Backbone of the agent is this schema file


from pydantic import BaseModel, Field   # import the necessary classes from pydantic
from typing import Annotated, Literal   # import the necessary classes from typing
from operator import add

class AgentSchema(BaseModel): #This is the schema for the agent
    messages : list = Field(..., description="Lisy of messages to be processed by the agent")
    user_question : str = Field(..., description="The original question asked by the user")
    curated_ques : str = Field(..., description="Curated user question")
    prompt_query_context : str = Field(...,description="A detailed prompt with SQL DB context that will help agent to generate SQL query")
    generated_sql_query : str = Field(...,description="Generated SQL query generated by the agent based on the curated question AND the prompt query context")
    is_safe : Literal["YES","NO"] = Field(...,description="Indicates whether the generated query is safe or not")
    comments : str = Field(...,description="Additional comment or feedback from the judge regarding the SQL query")
    sql_query_execution_result : str = Field(...,description="The result of the SQL query execution")
    final_answer : str = Field(...,description="Final answer generated by the agent based on the curated question AND the prompt query context")


class JudgeSchema(BaseModel): #This is the schema for the judge
    answer : Literal["YES","NO"] = Field(...,description="Indicates whether the generated query is safe to execute or not")
    comments : str = Field(...,description="Additional comment or feedback from the judge regarding the SQL query")


class ETLAgentSchema(BaseModel): #This is the schema for the agent
    messages : Annotated[list,add] = Field(..., description="List of messages to be processed by the agent")

class RouterSchema(BaseModel): #This is the schema for the router
    answer : Literal["sql","etl"] = Field(...,description="Indicates whether the generated query is safe to execute or not")
    comments : str = Field(...,description="Additional comment or feedback from the judge regarding the SQL query")

class DataAgentSchema(BaseModel): #This is the schema for the agent
    messages : list = Field(..., description="List of messages to be processed by the agent")
    route_response : str = Field(...,description="The route response generated by the router")